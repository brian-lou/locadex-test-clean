import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { getLocale, getGT } from "gt-next/server";
import { GTProvider, LocaleSelector } from "gt-next";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"]
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"]
});

async function getMetadata(): Promise<Metadata> {
  const t = await getGT();
  return {
    title: t("Create Next App"),
    description: t("Generated by create next app")
  };
}

export const metadata: Metadata = await getMetadata();

export default async function RootLayout({
  children


}: Readonly<{children: React.ReactNode;}>) {
  return (
  <html lang={await getLocale()}>
      <body
      className={`${geistSans.variable} ${geistMono.variable} antialiased`}><GTProvider>
        <header className="fixed top-0 right-0 p-4 z-10">
          <LocaleSelector />
        </header>
        {children}
      </GTProvider></body>
    </html>
  );
}